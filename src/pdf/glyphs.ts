const TABLES: Record<SymbolFamily, ReadonlyMap<number, number>> = {
  Symbol: SYMBOL,
  ZapfDingbats: ZAPF_DINGBATS,
  Wingdings: WINGDINGS,
  "MT Extra": MT_EXTRA,
};

/**
 * The family a font's name says it is: `ABCDEE+SymbolMT` and `Symbol,Bold`
 * are Symbol, `Wingdings-Regular` is Wingdings. `Wingdings 2` and `3` are other
 * fonts with other glyphs, and are not Wingdings.
 */
export function symbolFamily(fontName: string | undefined): SymbolFamily | undefined {
  if (!fontName) return undefined;
  const bare = fontName
    .replace(/^[A-Z]{6}\+/, "")
    .replace(/\s+/g, "")
    .toLowerCase();
  if (/^mt-?extra/.test(bare)) return "MT Extra";
  const name = bare.replace(/[,-].*$/, "");
  if (name === "symbol" || name === "symbolmt" || name === "symbolstd") return "Symbol";
  if (name === "zapfdingbats" || name === "dingbats" || name === "itczapfdingbats")
    return "ZapfDingbats";
  if (name === "wingdings") return "Wingdings";
  return undefined;
}

/** A symbol font's private-use characters: what needs the font's name to read. */
export const FONT_PRIVATE_USE = /[\uF020-\uF0FF]/u;
/** Anything mapGlyphs may change. */
export const SYMBOL_PRIVATE_USE = /[\uF020-\uF0FF\uF6D9-\uF6DB\uF8E5-\uF8FE]/u;

/** What was mapped on a page (or a document), by font family; what was not, by font, with its code points. */
export interface GlyphReport {
  mapped: Map<string, number>;
  unmapped: Map<string, Set<number>>;
}

export const emptyGlyphReport = (): GlyphReport => ({ mapped: new Map(), unmapped: new Map() });

/**
 * One run's text with its symbol font's private-use characters read through the
 * font's encoding. `fontName` is the font's own name (`ABCDEE+Symbol`), when the
 * page's operator list gave one.
 */
export function mapGlyphs(text: string, fontName: string | undefined, report: GlyphReport): string {
  if (!SYMBOL_PRIVATE_USE.test(text)) return text;
  const family = symbolFamily(fontName);
  let out = "";
  for (const char of text) {
    const point = char.codePointAt(0) ?? 0;
    const adobe = ADOBE_SYMBOL.get(point);
    if (adobe !== undefined) {
      out += String.fromCodePoint(adobe);
      report.mapped.set("Symbol", (report.mapped.get("Symbol") ?? 0) + 1);
      continue;
    }
    if (point >= 0xf020 && point <= 0xf0ff) {
      const mapped = family ? TABLES[family].get(point - 0xf000) : undefined;
      if (mapped !== undefined) {
        out += String.fromCodePoint(mapped);
        report.mapped.set(family!, (report.mapped.get(family!) ?? 0) + 1);
        continue;
      }
      const key = family ?? fontName?.replace(/^[A-Z]{6}\+/, "") ?? "an unnamed font";
      const codes = report.unmapped.get(key) ?? new Set<number>();
      codes.add(point);
      report.unmapped.set(key, codes);
    }
    out += char;
  }
  return out;
}

/** Adds one page's report to a document's. */
export function mergeGlyphReport(into: GlyphReport, from: GlyphReport | undefined): void {
  if (!from) return;
  for (const [family, count] of from.mapped)
    into.mapped.set(family, (into.mapped.get(family) ?? 0) + count);
  for (const [font, codes] of from.unmapped) {
    const set = into.unmapped.get(font) ?? new Set<number>();
    for (const code of codes) set.add(code);
    into.unmapped.set(font, set);
  }
}

const sorted = (keys: Iterable<string>): string[] =>
  [...keys].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const u = (point: number): string => `U+${point.toString(16).toUpperCase().padStart(4, "0")}`;

/** AP051 for what was mapped, AP052 for what was left: one each for the document. */
export function glyphDiagnostics(report: GlyphReport): DiagnosticInput[] {
  const out: DiagnosticInput[] = [];
  const total = [...report.mapped.values()].reduce((n, count) => n + count, 0);
  if (total)
    out.push({
      code: CODES.glyphsMapped,
      quality: "exact",
      message: `Mapped ${total} symbol-font glyph(s) to Unicode through their fonts' encodings: ${sorted(
        report.mapped.keys(),
      )
        .map((family) => `${family} ${report.mapped.get(family)}`)
        .join(", ")}`,
    });
  if (report.unmapped.size)
    out.push({
      code: CODES.glyphsUnmapped,
      quality: "approximate",
      message: `Private-use glyph(s) left as they were, with no Unicode for them in their font: ${sorted(
        report.unmapped.keys(),
      )
        .map((font) => {
          const codes = [...report.unmapped.get(font)!].sort((a, b) => a - b);
          return `${font} (${codes.slice(0, 8).map(u).join(" ")}${codes.length > 8 ? ` and ${codes.length - 8} more` : ""})`;
        })
        .join("; ")}`,
      remediation: "Read those characters from a render of the page (`cairn pdf render`).",
    });
  return out;
}
