/**
 * Symbol-font glyphs, mapped to Unicode.
 *
 * Word and most other producers write a Symbol, Wingdings, or similar font's
 * characters with a ToUnicode map (or a Microsoft symbol `cmap`) that puts them
 * in the private-use range U+F020–U+F0FF: the font's own byte plus 0xF000. The
 * text layer then carries U+F044 where the page shows Δ, and U+F0B7 where it
 * shows a bullet, and a search for "ΔV" never finds it. The byte means
 * something only in its font, so the font is looked up (the page's operator
 * list names it) and the byte read through that font's encoding. Adobe's own
 * private-use code points for Symbol's glyph pieces (U+F8E5–U+F8FE, the serif
 * ©®™ at U+F6D9–U+F6DB) come from glyph names and map whatever the font.
 *
 * What was mapped, and what was left as it was, is reported per font.
 *
 * The Symbol and ZapfDingbats tables are Adobe's encodings read through the
 * Adobe Glyph List (as pdf.js carries them), with Δ, Ω, and μ given their Greek
 * code points rather than the increment, ohm, and micro signs, and the glyph
 * pieces their Unicode bracket pieces. Wingdings follows Unicode's mapping of
 * it, less the two runs (0x96–0x9D, 0xCB–0xD4) whose glyphs are not settled
 * there. MT Extra maps only ℏ and ℓ so far; its other bytes are reported.
 */

